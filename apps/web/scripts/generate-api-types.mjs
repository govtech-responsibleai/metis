import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = new URL("../../../", import.meta.url);
const output = new URL("../src/generated/api.ts", import.meta.url);
const temp = mkdtempSync(join(tmpdir(), "metis-openapi-"));
const schema = join(temp, "openapi.json");
try {
  const python = spawnSync(
    ".venv/bin/python",
    [
      "-c",
      [
        "import json, sys",
        "from metis.api.main import create_app",
        "sys.stdout.write(json.dumps(create_app().openapi()))",
      ].join("; "),
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (python.status !== 0)
    throw new Error(python.stderr || "Could not create the API schema.");
  writeFileSync(schema, python.stdout);
  const generated = spawnSync(
    "npx",
    ["--no-install", "openapi-typescript", schema],
    { cwd: new URL("../", import.meta.url), encoding: "utf8" },
  );
  if (generated.status !== 0)
    throw new Error(generated.stderr || "Could not generate API types.");
  const content = `// Generated by npm run generate:api. Do not edit by hand.\n${generated.stdout}`;
  if (process.argv.includes("--check")) {
    const current = readFileSync(output, "utf8");
    if (current !== content) {
      console.error("src/generated/api.ts is stale; run npm run generate:api");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(output, content);
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}
